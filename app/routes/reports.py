@reports_bp.get(
    "/reports/cases/<int:case_id>/summary.pdf"
)
@roles_required(
    UserRole.STUDENT,
    UserRole.COUNSELOR,
    UserRole.HEAD_COUNSELOR,
    UserRole.ADMIN
)
def case_summary(case_id):

    case = db.session.get(
        CounselingCase,
        case_id,
    )

    user = current_user()

    if not case:

        return error(
            "Case not found.",
            404,
            "not_found",
        )

    if not can_access_case(
        user,
        case,
    ):

        return error(
            "You do not have access to this case.",
            403,
            "forbidden",
        )

    pseudonym = (
        f"STUDENT-{case.student_id:05d}"
    )

    audit(
        "CASE_SUMMARY_GENERATED",
        "case",
        case.id,
        user.id,
    )

    db.session.commit()

    pdf = make_case_summary_pdf(
        case
    )

    return send_file(
        pdf,
        mimetype="application/pdf",
        as_attachment=True,
        download_name=(
            f"case-summary-{case.case_number}.pdf"
        ),
    )

