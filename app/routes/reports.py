# SHARED / GENERIC PDF
# Used by Case Summary and Clearance Certificate for now.
# =========================================================

def make_pdf(title, rows, confidentiality=None):

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )

    styles = getSampleStyleSheet()

    story = [
        Paragraph(
            "UNIVERSITY GUIDANCE & COUNSELING",
            styles["Heading2"],
        ),
        Spacer(1, 5 * mm),
        Paragraph(
            title,
            styles["Title"],
        ),
    ]

    if confidentiality:

        story += [
            Spacer(1, 3 * mm),
            Paragraph(
                confidentiality,
                styles["Italic"],
            ),
        ]

    story += [
        Spacer(1, 8 * mm)
    ]

    data = [
        [
            Paragraph(
                f"<b>{label}</b>",
                styles["BodyText"],
            ),
            Paragraph(
                str(value or "—"),
                styles["BodyText"],
            ),
        ]
        for label, value in rows
    ]

    table = Table(
        data,
        colWidths=[
            55 * mm,
            105 * mm,
        ],
    )

    table.setStyle(
        TableStyle([
            (
                "VALIGN",
                (0, 0),
                (-1, -1),
                "TOP",
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.4,
                colors.HexColor("#B9C4CC"),
            ),
            (
                "BACKGROUND",
                (0, 0),
                (0, -1),
                colors.HexColor("#E9F5F2"),
            ),
            (
                "LEFTPADDING",
                (0, 0),
                (-1, -1),
                7,
            ),
            (
                "RIGHTPADDING",
                (0, 0),
                (-1, -1),
                7,
            ),
            (
                "TOPPADDING",
                (0, 0),
                (-1, -1),
                5,
            ),
            (
                "BOTTOMPADDING",
                (0, 0),
                (-1, -1),
                5,
            ),
        ])
    )

    story += [
        table,
        Spacer(1, 18 * mm),
        Paragraph(
            "Generated by the University Guidance & Counseling Management System",
            styles["Italic"],
        ),
    ]

    doc.build(story)

    buffer.seek(0)

    return buffer


# =========================================================
# DATE / TIME FORMATTERS
# =========================================================

def format_document_date(value):

    if not value:
        return "—"

    return value.strftime(
        "%B %d, %Y"
    )


def format_document_time(value):

    if not value:
        return "—"

    # %I gives 12-hour time.
    # lstrip removes the leading zero from values such as 09:00 AM.
    return value.strftime(
        "%I:%M %p"
    ).lstrip("0")


