@reports_bp.get(
    "/reports/clearances/<int:clearance_id>/certificate.pdf"
)
@roles_required(
    UserRole.STUDENT,
    UserRole.HEAD_COUNSELOR,
    UserRole.ADMIN,
    UserRole.STAFF,
)
def clearance_certificate(clearance_id):

    clearance = db.session.get(
        Clearance,
        clearance_id,
    )

    user = current_user()

    if not clearance:

        return error(
            "Clearance record not found.",
            404,
            "not_found",
        )

    if (
        user.role == UserRole.STUDENT
        and clearance.student_id
        != user.student_profile.id
    ):

        return error(
            "You do not have access to this clearance.",
            403,
            "forbidden",
        )

    if (
        clearance.status
        != ClearanceStatus.CLEARED
    ):

        return error(
            "Certificate is unavailable until the student is cleared.",
            409,
            "not_cleared",
        )

    audit(
        "CLEARANCE_CERTIFICATE_GENERATED",
        "clearance",
        clearance.id,
        user.id,
    )

    db.session.commit()

    pdf = make_clearance_certificate_pdf(
        clearance
    )

    return send_file(
        pdf,
        mimetype="application/pdf",
        as_attachment=True,
        download_name=(
            f"clearance-{clearance.certificate_number}.pdf"
        ),
    )