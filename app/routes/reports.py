@reports_bp.get(
    "/reports/appointments/<int:appointment_id>/confirmation.pdf"
)
@roles_required(
    UserRole.STUDENT,
    UserRole.COUNSELOR,
    UserRole.HEAD_COUNSELOR,
    UserRole.ADMIN,
    UserRole.STAFF,
)
def appointment_confirmation(appointment_id):

    appointment = db.session.get(
        Appointment,
        appointment_id,
    )

    user = current_user()

    if not appointment:

        return error(
            "Appointment not found.",
            404,
            "not_found",
        )

    participant = (
        user.role in {
            UserRole.HEAD_COUNSELOR,
            UserRole.ADMIN,
            UserRole.STAFF,
        }
    )

    participant |= (
        user.role == UserRole.STUDENT
        and appointment.student_id
        == user.student_profile.id
    )

    participant |= (
        user.role == UserRole.COUNSELOR
        and appointment.counselor_id
        == user.counselor_profile.id
    )

    if not participant:

        return error(
            "You do not have access to this appointment.",
            403,
            "forbidden",
        )

    audit(
        "APPOINTMENT_SLIP_GENERATED",
        "appointment",
        appointment.id,
        user.id,
    )

    db.session.commit()

    pdf = make_appointment_confirmation_pdf(
        appointment
    )

    return send_file(
        pdf,
        mimetype="application/pdf",
        as_attachment=True,
        download_name=(
            "guidance-appointment-confirmation.pdf"
        ),
    )

